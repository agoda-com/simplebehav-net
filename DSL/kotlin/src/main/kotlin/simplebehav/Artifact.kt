package simplebehav

import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.add
import kotlinx.serialization.json.addJsonObject
import kotlinx.serialization.json.buildJsonArray
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.time.Instant
import java.util.UUID
import kotlin.reflect.KClass

@Serializable
enum class StepType { Setup, Act, Assert }

@Serializable
data class ArtifactStep(
    val type: StepType,
    val label: String,
    val durationMs: Long,
    val error: String? = null,
)

@Serializable
data class ArtifactBundle(
    val id: String,
    val title: String,
    val status: String,
    val startedAt: String,
    val durationMs: Long,
    val steps: List<ArtifactStep>,
)

private val artifactJson = Json {
    prettyPrint = true
    explicitNulls = false
}

private val pretty = Json { prettyPrint = true }

internal object ArtifactPaths {
    fun slug(value: String): String {
        val cleaned = value.lowercase().replace(' ', '-').replace(Regex("[^a-z0-9-]"), "")
        if (cleaned.length <= 80) return cleaned
        val hash = MessageDigest.getInstance("SHA-256")
            .digest(value.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
            .take(8)
        return cleaned.take(71) + "-" + hash
    }

    fun suitePath(projectName: String, testClass: KClass<*>?): List<String> {
        val project = segment(projectName)
        if (testClass == null) return listOf(project)
        val packages = testClass.java.packageName.split('.').filter { it.isNotEmpty() }.map(::segment)
        val file = segment(testClass.simpleName ?: "suite")
        return listOf(project) + packages + file
    }

    private fun segment(value: String): String {
        val cleaned = value.replace(Regex("[^A-Za-z0-9._-]"), "-")
        return cleaned.ifEmpty { "suite" }
    }
}

internal class ArtifactEmitter(private val title: String) {
    private val id = UUID.randomUUID().toString()
    private val startedAt = System.currentTimeMillis()
    private val steps = mutableListOf<ArtifactStep>()

    fun add(step: ArtifactStep) {
        steps += step
    }

    fun build(status: String) = ArtifactBundle(
        id = id,
        title = title,
        status = status,
        startedAt = Instant.ofEpochMilli(startedAt).toString(),
        durationMs = System.currentTimeMillis() - startedAt,
        steps = steps.toList(),
    )

    /** Writes bundle.json and cucumber.json. The runner then refreshes the suite index.html. */
    fun emit(bundle: ArtifactBundle, outDir: String, suitePath: List<String>): Path {
        val slug = ArtifactPaths.slug(bundle.title)
        val dir = suitePath.fold(Path.of(outDir)) { path, segment -> path.resolve(segment) }.resolve(slug)
        Files.createDirectories(dir)
        Files.writeString(dir.resolve("bundle.json"), artifactJson.encodeToString(bundle))
        Files.writeString(dir.resolve("cucumber.json"), cucumber(bundle, suitePath, slug))
        return dir
    }

    private fun cucumber(bundle: ArtifactBundle, suitePath: List<String>, slug: String): String {
        val document = buildJsonArray {
            addJsonObject {
                put("uri", suitePath.joinToString("/") + "/$slug")
                put("id", bundle.id)
                put("keyword", "Feature")
                put("name", suitePath.last())
                put("line", 1)
                put("description", "Generated by SimpleBehav")
                put("elements", buildJsonArray {
                    addJsonObject {
                        put("id", "${bundle.id};$slug")
                        put("keyword", "Scenario")
                        put("name", bundle.title)
                        put("line", 1)
                        put("type", "scenario")
                        put("steps", buildJsonArray {
                            bundle.steps.forEachIndexed { index, step ->
                                addJsonObject {
                                    put("keyword", when (step.type) {
                                        StepType.Setup -> "Given "
                                        StepType.Act -> "When "
                                        StepType.Assert -> "Then "
                                    })
                                    put("name", step.label)
                                    put("line", index + 1)
                                    put("result", buildJsonObject {
                                        put("duration", JsonPrimitive(step.durationMs * 1_000_000))
                                        put("status", if (step.error == null) "passed" else "failed")
                                        if (step.error != null) put("error_message", step.error)
                                    })
                                }
                            }
                        })
                    }
                })
            }
        }
        return pretty.encodeToString(kotlinx.serialization.json.JsonElement.serializer(), document)
    }
}
